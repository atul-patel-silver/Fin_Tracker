// src/interfaces/auth.ts

// Backend DTO for Login
export interface LoginDto {
  userName: string;
  password: string;
}

// Backend DTO for Register (UserDTO)
export interface UserDTO {
  id?: number; // Optional as it might be generated by backend
  firstName: string;
  middleName?: string; // Optional field
  lastName: string;
  emailId: string;
  mobileNumber: string;
  userName: string;
  password?: string; // Optional if you handle password setting separately or don't send it back
  sub?: string; // Subject (e.g., for third-party login ID)
  loginType?: string; // e.g., "NORMAL", "GOOGLE", "FACEBOOK"
  isActive?: boolean;
  isDeleted?: boolean;
}

// Response from successful login
export interface AuthResponse {
  token: string;
  user: UserDTO; // Or a simplified user profile
}